"""Shared storage for the Vercel deployment. Render continues to use SQLite."""

import os
import secrets
from contextlib import contextmanager

CHUNK_BYTES = 3 * 1024 * 1024


class UploadError(ValueError):
    pass


@contextmanager
def connect():
    from psycopg import connect as open_connection
    from psycopg.rows import dict_row

    url = os.environ.get('DATABASE_URL')
    if not url:
        raise RuntimeError('Set DATABASE_URL to the pooled PostgreSQL connection URL')
    with open_connection(url, connect_timeout=8, row_factory=dict_row) as db:
        yield db


def init():
    with connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(721915042)')
        db.execute('''CREATE TABLE IF NOT EXISTS scans (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT NOT NULL, source TEXT NOT NULL, size_mb DOUBLE PRECISION,
            pages INTEGER, score INTEGER NOT NULL, class_id INTEGER NOT NULL,
            created_at TEXT NOT NULL)''')
        db.execute('''CREATE TABLE IF NOT EXISTS pdf_uploads (
            id TEXT PRIMARY KEY, filename TEXT NOT NULL, size INTEGER NOT NULL,
            prompt TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now())''')
        db.execute('''CREATE TABLE IF NOT EXISTS pdf_chunks (
            upload_id TEXT REFERENCES pdf_uploads(id) ON DELETE CASCADE,
            part INTEGER NOT NULL, payload BYTEA NOT NULL, PRIMARY KEY(upload_id, part))''')
        db.execute('''CREATE TABLE IF NOT EXISTS pdf_results (
            cache_key TEXT PRIMARY KEY, result JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now())''')
        db.execute('''CREATE TABLE IF NOT EXISTS login_attempts (
            id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now())''')


def record_scan(row):
    with connect() as db:
        db.execute('''INSERT INTO scans(kind, source, size_mb, pages, score, class_id, created_at)
                      VALUES (%s, %s, %s, %s, %s, %s, %s)''', row)


def recent_scans():
    with connect() as db:
        return db.execute('SELECT * FROM scans ORDER BY id DESC LIMIT 20').fetchall()


def allow_login_attempt():
    with connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(721915043)')
        db.execute("DELETE FROM login_attempts WHERE created_at < now() - interval '5 minutes'")
        if db.execute('SELECT count(*) AS total FROM login_attempts').fetchone()['total'] >= 10:
            return False
        db.execute('INSERT INTO login_attempts DEFAULT VALUES')
        return True


def clear_login_attempts():
    with connect() as db:
        db.execute('DELETE FROM login_attempts')


def start_upload(filename, size, prompt):
    upload_id = secrets.token_urlsafe(24)
    with connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(721915044)')
        db.execute("DELETE FROM pdf_uploads WHERE created_at < now() - interval '15 minutes'")
        if db.execute('SELECT count(*) AS total FROM pdf_uploads').fetchone()['total'] >= 3:
            raise UploadError('Талдау кезегі толы. Сәлден кейін қайта көріңіз.')
        db.execute('INSERT INTO pdf_uploads(id, filename, size, prompt) VALUES (%s, %s, %s, %s)',
                   (upload_id, filename, size, prompt))
    return upload_id


def lock_upload(db, upload_id):
    row = db.execute("""SELECT filename, size, prompt FROM pdf_uploads
                         WHERE id = %s AND created_at >= now() - interval '15 minutes'
                         FOR UPDATE""", (upload_id,)).fetchone()
    if row is None:
        raise UploadError('Жүктеу табылмады. Қайта бастаңыз.')
    return row


def put_chunk(upload_id, part, payload):
    with connect() as db:
        upload = lock_upload(db, upload_id)
        expected = min(CHUNK_BYTES, upload['size'] - part * CHUNK_BYTES)
        if part < 0 or expected <= 0 or len(payload) != expected:
            raise UploadError('Файл бөлігінің көлемі дұрыс емес.')
        if part == 0 and not payload.startswith(b'%PDF-'):
            raise UploadError('Таңдалған файл жарамды PDF емес.')
        db.execute('''INSERT INTO pdf_chunks(upload_id, part, payload) VALUES (%s, %s, %s)
                      ON CONFLICT (upload_id, part) DO UPDATE SET payload = EXCLUDED.payload''',
                   (upload_id, part, payload))


def take_upload(upload_id):
    with connect() as db:
        upload = lock_upload(db, upload_id)
        rows = db.execute('SELECT payload FROM pdf_chunks WHERE upload_id = %s ORDER BY part',
                          (upload_id,)).fetchall()
        data = b''.join(row['payload'] for row in rows)
        if len(data) != upload['size'] or not data.startswith(b'%PDF-'):
            raise UploadError('PDF толық жүктелмеді. Қайта көріңіз.')
        db.execute('DELETE FROM pdf_uploads WHERE id = %s', (upload_id,))
    return data, upload['filename'], upload['prompt']


def cancel_upload(upload_id):
    with connect() as db:
        db.execute('DELETE FROM pdf_uploads WHERE id = %s', (upload_id,))


def cached_result(key):
    with connect() as db:
        row = db.execute("""SELECT result FROM pdf_results WHERE cache_key = %s
                            AND created_at >= now() - interval '15 minutes'""", (key,)).fetchone()
    return row['result'] if row else None


def cache_result(key, result):
    from psycopg.types.json import Jsonb

    with connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(721915045)')
        db.execute("DELETE FROM pdf_results WHERE created_at < now() - interval '15 minutes'")
        db.execute('''INSERT INTO pdf_results(cache_key, result) VALUES (%s, %s)
                      ON CONFLICT (cache_key) DO UPDATE SET result = EXCLUDED.result, created_at = now()''',
                   (key, Jsonb(result)))
        db.execute('''DELETE FROM pdf_results WHERE cache_key IN
                      (SELECT cache_key FROM pdf_results ORDER BY created_at DESC OFFSET 8)''')
